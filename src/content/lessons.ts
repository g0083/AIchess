/**
 * Learn mode: nine classes, from absolute beginner to advanced reference.
 *
 * Each lesson is prose split into short lines, plus a board exercise the player
 * must actually perform, and a comprehension quiz. The prose is deliberately
 * concise so it stays correct and scannable on any screen.
 */

export interface LessonStep {
  /** A heading or a short instruction line. */
  heading: string;
  /** Bullet lines. */
  lines?: string[];
}

export interface BoardTask {
  /** Position to set up. */
  fen: string;
  prompt: string;
  /** Legal moves that complete the task, in SAN. */
  accept: string[];
  /** What the learner should understand. */
  explain: string;
}

export interface QuizQuestion {
  question: string;
  choices: string[];
  /** Index into choices. */
  answer: number;
  explain: string;
}

export interface Lesson {
  id: string;
  classLevel: number;
  title: string;
  summary: string;
  minutes: number;
  steps: LessonStep[];
  task?: BoardTask;
  quiz?: QuizQuestion[];
}

export interface ClassLevel {
  level: number;
  title: string;
  subtitle: string;
  goal: string;
}

